bool MannyBoard::initNvs() {
    if (nvs_initialized) {
        LOG_INFO(TAG, "NVS already initialized");
        return true;
    }

    // Treat the configured NVS partition as a board dependency and fail early
    // when the partition table does not provide it.
    const esp_partition_t *nvs_partition = esp_partition_find_first(
        ESP_PARTITION_TYPE_DATA,
        ESP_PARTITION_SUBTYPE_DATA_NVS,
        "nvs");
    if (nvs_partition == nullptr) {
        LOG_ERROR(TAG, "Required NVS partition 'nvs' was not found");
        return false;
    }

    esp_err_t ret = nvs_flash_init();
    if (ret == ESP_ERR_NVS_NO_FREE_PAGES || ret == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        LOG_WARNING(TAG, "NVS needs erase before initialization: %s", esp_err_to_name(ret));
        ret = nvs_flash_erase();
        if (ret != ESP_OK) {
            LOG_ERROR(TAG, "nvs_flash_erase failed: %s", esp_err_to_name(ret));
            return false;
        }
        ret = nvs_flash_init();
    }
    if (ret != ESP_OK) {
        LOG_ERROR(TAG, "nvs_flash_init failed: %s", esp_err_to_name(ret));
        return false;
    }

    nvs_initialized = true;
    LOG_INFO(TAG, "NVS initialized from partition '%s'", nvs_partition->label);
    return true;
}

bool MannyBoard::isNvsReady() const {
    return nvs_initialized;
}

bool MannyBoard::initNetworking() {
    if (networking_initialized) {
        LOG_INFO(TAG, "Networking already initialized");
        return true;
    }

    // WiFi depends on NVS, esp-netif, and the default event loop. Keeping this
    // sequence here prevents callers from duplicating low-level ESP-IDF setup.
    if (!initNvs()) {
        return false;
    }

    esp_err_t ret = esp_netif_init();
    if (ret != ESP_OK && ret != ESP_ERR_INVALID_STATE) {
        LOG_ERROR(TAG, "esp_netif_init failed: %s", esp_err_to_name(ret));
        return false;
    }
    if (ret == ESP_ERR_INVALID_STATE) {
        LOG_INFO(TAG, "esp_netif already initialized");
    }

    ret = esp_event_loop_create_default();
    if (ret != ESP_OK && ret != ESP_ERR_INVALID_STATE) {
        LOG_ERROR(TAG, "esp_event_loop_create_default failed: %s", esp_err_to_name(ret));
        return false;
    }
    if (ret == ESP_ERR_INVALID_STATE) {
        LOG_INFO(TAG, "default event loop already exists");
    }

    wifi_init_config_t wifi_init_config = WIFI_INIT_CONFIG_DEFAULT();
    ret = esp_wifi_init(&wifi_init_config);
    if (ret != ESP_OK && ret != ESP_ERR_WIFI_INIT_STATE) {
        LOG_ERROR(TAG, "esp_wifi_init failed: %s", esp_err_to_name(ret));
        return false;
    }
    if (ret == ESP_ERR_WIFI_INIT_STATE) {
        LOG_INFO(TAG, "WiFi already initialized");
    }

    networking_initialized = true;
    return true;
}

bool MannyBoard::startWifiSta() {
    if (!initNetworking()) {
        return false;
    }

    if (sta_netif == nullptr) {
        sta_netif = esp_netif_create_default_wifi_sta();
    }

    esp_err_t ret = esp_wifi_set_mode(WIFI_MODE_STA);
    if (ret != ESP_OK) {
        LOG_ERROR(TAG, "esp_wifi_set_mode STA failed: %s", esp_err_to_name(ret));
        return false;
    }

    ret = esp_wifi_start();
    if (ret != ESP_OK && ret != ESP_ERR_WIFI_NOT_STOPPED) {
        LOG_ERROR(TAG, "esp_wifi_start failed: %s", esp_err_to_name(ret));
        return false;
    }
    if (ret == ESP_ERR_WIFI_NOT_STOPPED) {
        LOG_INFO(TAG, "WiFi STA already started");
    }

    wifi_started = true;
    wifi_ip_address[0] = '\0';
    uint8_t mac[6] = {};
    if (esp_wifi_get_mac(WIFI_IF_STA, mac) == ESP_OK) {
        snprintf(wifi_mac_address, sizeof(wifi_mac_address), "%02x:%02x:%02x:%02x:%02x:%02x",
                 mac[0], mac[1], mac[2], mac[3], mac[4], mac[5]);
    }
    ret = esp_wifi_disconnect();
    if (ret != ESP_OK && ret != ESP_ERR_WIFI_NOT_INIT && ret != ESP_ERR_WIFI_CONN) {
        LOG_WARNING(TAG, "esp_wifi_disconnect returned: %s", esp_err_to_name(ret));
    }
    return true;
}

bool MannyBoard::startWifiSoftAp() {
    if (!initNetworking()) {
        return false;
    }

    // AP credentials and network parameters come from Kconfig-generated
    // sdkconfig values. Private overrides belong in the ignored sdkconfig file.
    const MannyWifiApConfig cfg = getDefaultApConfig();

    if (ap_netif == nullptr) {
        ap_netif = esp_netif_create_default_wifi_ap();
        if (ap_netif == nullptr) {
            LOG_ERROR(TAG, "Failed to create default WiFi AP netif");
            return false;
        }
    }

    wifi_config_t wifi_config = {};
    snprintf(reinterpret_cast<char *>(wifi_config.ap.ssid), sizeof(wifi_config.ap.ssid), "%s", cfg.ssid);
    snprintf(reinterpret_cast<char *>(wifi_config.ap.password), sizeof(wifi_config.ap.password), "%s", cfg.password);
    wifi_config.ap.ssid_len = strlen(cfg.ssid);
    wifi_config.ap.channel = cfg.channel;
    wifi_config.ap.max_connection = cfg.max_connections;
    wifi_config.ap.authmode = strlen(cfg.password) == 0 ? WIFI_AUTH_OPEN : WIFI_AUTH_WPA2_WPA3_PSK;

    esp_err_t ret = esp_wifi_set_mode(WIFI_MODE_AP);
    if (ret != ESP_OK) {
        LOG_ERROR(TAG, "esp_wifi_set_mode AP failed: %s", esp_err_to_name(ret));
        return false;
    }

    ret = esp_netif_dhcps_stop(ap_netif);
    if (ret != ESP_OK && ret != ESP_ERR_ESP_NETIF_DHCP_ALREADY_STOPPED) {
        LOG_ERROR(TAG, "esp_netif_dhcps_stop failed: %s", esp_err_to_name(ret));
        return false;
    }

    esp_netif_ip_info_t ip_info = {};
    if (esp_netif_str_to_ip4(cfg.ip, &ip_info.ip) != ESP_OK ||
        esp_netif_str_to_ip4(cfg.ip, &ip_info.gw) != ESP_OK ||
        esp_netif_str_to_ip4(cfg.netmask, &ip_info.netmask) != ESP_OK) {
        LOG_ERROR(TAG, "Invalid SoftAP IP configuration: ip=%s netmask=%s", cfg.ip, cfg.netmask);
        return false;
    }

    ret = esp_netif_set_ip_info(ap_netif, &ip_info);
    if (ret != ESP_OK) {
        LOG_ERROR(TAG, "esp_netif_set_ip_info AP failed: %s", esp_err_to_name(ret));
        return false;
    }

    ret = esp_netif_dhcps_start(ap_netif);
    if (ret != ESP_OK && ret != ESP_ERR_ESP_NETIF_DHCP_ALREADY_STARTED) {
        LOG_ERROR(TAG, "esp_netif_dhcps_start failed: %s", esp_err_to_name(ret));
        return false;
    }

    ret = esp_wifi_set_config(WIFI_IF_AP, &wifi_config);
    if (ret != ESP_OK) {
        LOG_ERROR(TAG, "esp_wifi_set_config AP failed: %s", esp_err_to_name(ret));
        return false;
    }

    ret = esp_wifi_start();
    if (ret != ESP_OK && ret != ESP_ERR_WIFI_NOT_STOPPED) {
        LOG_ERROR(TAG, "esp_wifi_start AP failed: %s", esp_err_to_name(ret));
        return false;
    }
    if (ret == ESP_ERR_WIFI_NOT_STOPPED) {
        LOG_INFO(TAG, "WiFi SoftAP already started");
    }

    wifi_started = true;
    snprintf(wifi_ip_address, sizeof(wifi_ip_address), "%s", cfg.ip);
    uint8_t mac[6] = {};
    if (esp_wifi_get_mac(WIFI_IF_AP, mac) == ESP_OK) {
        snprintf(wifi_mac_address, sizeof(wifi_mac_address), "%02x:%02x:%02x:%02x:%02x:%02x",
                 mac[0], mac[1], mac[2], mac[3], mac[4], mac[5]);
    }
    LOG_INFO(TAG, "SoftAP started: ssid=%s ip=%s channel=%u max_sta=%u",
             cfg.ssid, cfg.ip, cfg.channel, cfg.max_connections);
    return true;
}

bool MannyBoard::stopWifi() {
    if (!networking_initialized || !wifi_started) {
        return true;
    }
    esp_err_t ret = esp_wifi_stop();
    if (ret != ESP_OK && ret != ESP_ERR_WIFI_NOT_INIT) {
        LOG_ERROR(TAG, "esp_wifi_stop failed: %s", esp_err_to_name(ret));
        return false;
    }
    wifi_started = false;
    wifi_ip_address[0] = '\0';
    return true;
}

