static const char *TAG = "MannyBoard";

/**
 * @brief SoftAP values read from sdkconfig.
 */
struct MannyWifiApConfig {
    const char* ssid;
    const char* password;
    const char* ip;
    const char* netmask;
    uint8_t channel;
    uint8_t max_connections;
};

static_assert(sizeof(CONFIG_ROCKET_AP_SSID) > 1,
              "CONFIG_ROCKET_AP_SSID must not be empty");
static_assert(sizeof(CONFIG_ROCKET_AP_PASSWORD) == 1 ||
              sizeof(CONFIG_ROCKET_AP_PASSWORD) >= 9,
              "CONFIG_ROCKET_AP_PASSWORD must be empty or at least 8 characters");

/**
 * @brief Return the default Manny SoftAP configuration generated by Kconfig.
 */
static MannyWifiApConfig getDefaultApConfig()
{
    return {
        CONFIG_ROCKET_AP_SSID,
        CONFIG_ROCKET_AP_PASSWORD,
        CONFIG_ROCKET_AP_IP_ADDR,
        CONFIG_ROCKET_AP_NETMASK,
        static_cast<uint8_t>(CONFIG_ROCKET_AP_CHANNEL),
        static_cast<uint8_t>(CONFIG_ROCKET_AP_MAX_CONNECTIONS),
    };
}

